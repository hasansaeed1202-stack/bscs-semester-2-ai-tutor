import { readFile, writeFile, mkdir } from 'node:fs/promises'
import { createHash } from 'node:crypto'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const catalog = [
  ['digital-logic-design', 'digital-logic-design.md'],
  ['discrete-mathematics', 'discrete-mathematics.md'],
  ['expository-writing', 'expository-writing.md'],
  ['ideology-constitution-pakistan', 'ideology-constitution-pakistan.md'],
  ['mathematics-2', 'mathematics-2.md'],
  ['oop', 'oop.md'],
  ['probability-and-statistics', 'probability-and-statistics.md'],
]

export function slugify(value) {
  return value.toLowerCase().normalize('NFKD').replace(/[’']/g, '').replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '')
}

const assessmentPattern = /^(assignment|quiz|presentations?)(?:\s*#?\d+)?$/i
const examPattern = /(mid|final|end).*(exam|term)|examination/i

export function parseSyllabus(markdown, subjectSlug = 'subject') {
  const lines = markdown.split(/\r?\n/)
  const start = lines.findIndex((line) => /^## Week-wise (Plan|Breakdown)\s*$/.test(line.trim()))
  if (start < 0) throw new Error(`${subjectSlug}: missing week-wise plan`)
  const units = []
  let unit = null
  let parentTopic = null
  let topicIndex = 0

  const addMilestone = (title, label = null) => {
    units.push({ id: `${subjectSlug}-milestone-${units.length + 1}`, type: 'milestone', title, label })
  }

  for (let i = start + 1; i < lines.length; i += 1) {
    const line = lines[i]
    if (/^##\s+/.test(line)) break
    const heading = line.match(/^###\s+(.+?)\s*$/)
    if (heading) {
      const title = heading[1]
      if (examPattern.test(title)) {
        addMilestone(title)
        unit = null
      } else if (/^Weeks?\s+/i.test(title)) {
        unit = { id: `${subjectSlug}-${slugify(title)}`, type: 'week', title, topics: [], assessments: [], milestones: [] }
        units.push(unit)
      } else {
        unit = null
      }
      parentTopic = null
      continue
    }
    if (!unit) continue
    const bullet = line.match(/^(\s*)-\s+(.+?)\s*$/)
    if (!bullet) continue
    const indent = bullet[1].length
    const title = bullet[2]
    if (assessmentPattern.test(title)) {
      unit.assessments.push(title)
      continue
    }
    if (examPattern.test(title)) {
      unit.milestones.push(title)
      continue
    }
    topicIndex += 1
    const topic = { id: `${subjectSlug}-topic-${topicIndex}-${slugify(title)}`, title }
    if (indent > 0 && parentTopic) {
      parentTopic.children ??= []
      parentTopic.children.push(topic)
    } else {
      unit.topics.push(topic)
      parentTopic = topic
    }
  }
  const topicCount = units.reduce((sum, item) => sum + (item.topics?.reduce((count, topic) => count + 1 + (topic.children?.length ?? 0), 0) ?? 0), 0)
  if (!topicCount) throw new Error(`${subjectSlug}: no curriculum topics found`)
  return { subjectSlug, units, topicCount }
}

await mkdir(resolve(root, 'src/data/syllabi'), { recursive: true })
await mkdir(resolve(root, 'worker/curricula'), { recursive: true })
const backendCurricula = {}
for (const [slug, filename] of catalog) {
  const markdown = await readFile(resolve(root, filename), 'utf8')
  const parsed = parseSyllabus(markdown, slug)
  await writeFile(resolve(root, `src/data/syllabi/${slug}.json`), `${JSON.stringify(parsed, null, 2)}\n`)
  const curriculum = { ...parsed, curriculumVersion: createHash('sha256').update(JSON.stringify(parsed)).digest('hex') }
  backendCurricula[slug] = curriculum
  await writeFile(resolve(root, `worker/curricula/${slug}.json`), `${JSON.stringify(curriculum, null, 2)}\n`)
}
await writeFile(resolve(root, 'worker/curricula/index.js'), `// Generated by scripts/build-syllabus-data.mjs. Do not edit.\nexport const curricula = Object.freeze(${JSON.stringify(backendCurricula, null, 2)})\n`)
console.log(`Generated ${catalog.length} syllabus data files.`)
